#!/usr/bin/env python3
"""Write the pgfplots sources of the numerical figures from the SDP output.

Reads data/frontier_global.csv and data/crossover.csv and writes
numerics_frontier.tex and numerics_crossover.tex with the points embedded as
inline \\addplot tables.  By default the files are tikzpicture snippets in
../figures/ (like ../numerical-check/export_tex.py); with --standalone they are
complete documents that \\input a preamble.tex (as used for the manuscript).

Usage: python3 figure_data.py [--data DIR] [--out DIR] [--standalone]  Analytic
curves (Phi, sigma_*, delta^2/B, 1 + c_3 delta) are drawn by pgfplots itself;
sigma_* uses the parametrisation zeta = B*pi/(4*s) - 2*s^2/pi of the cubic
s^3 + (pi*zeta/2) s - B*pi^2/8 = 0.  Then build with: python3 rebuild.py numerics_*.tex
"""
import csv
from pathlib import Path
import numpy as np

here = Path(__file__).resolve().parent
data, figs, STANDALONE = here / "data", here.parent / "figures", False
PI = np.pi; B = 0.5 - 4 / PI**2; EPS = 0.5 - 1 / PI


def read(name):
    with open(data / name) as f:
        return list(csv.DictReader(f))


def table(header, rows):
    lines = [" ".join(header)] + [" ".join(f"{v:.8g}" for v in r) for r in rows]
    return "{\n" + "\n".join(lines) + "\n}"


GEN = "% Generated by figure_data.py from the SDP results -- do not edit by hand.\n"
DOC_HEAD = r"""\IfFileExists{figures/preamble.tex}{\input{figures/preamble.tex}}{\input{preamble.tex}}
\begin{document}
"""
# Snippets need: pgfplots with the groupplots library, amsmath, and \sgn defined
# (e.g. \DeclareMathOperator{\sgn}{sgn}).


def wrap(body):
    tikz = "\\begin{tikzpicture}\n" + body + "\\end{groupplot}\\end{tikzpicture}\n"
    return GEN + (DOC_HEAD + tikz + "\\end{document}\n" if STANDALONE else tikz)
LEG = r"legend style={font=\scriptsize,draw=none,fill=white,fill opacity=.85,text opacity=1}"
# sigma_* and Phi along the positive root, parametrised by s = sigma_*
PHI_PARAM = r"({(.5-4/pi^2)*pi/(4*\t)-2*\t^2/pi},{(.5-4/pi^2)*pi^2/(16*\t^2)-2*\t})"
SIG_PARAM = r"({(.5-4/pi^2)*pi/(4*\t)-2*\t^2/pi},{\t})"


def frontier():
    g = read("frontier_global.csv")
    N = max(int(r["N"]) for r in g)  # plot the finest truncation available
    curve = lambda mu: sorted((float(r["eps"]), float(r["dE_over_Ek"]))
                              for r in g if int(r["N"]) == N and float(r["mu"]) == mu)
    ratio = sorted((EPS - e, E * B / (EPS - e) ** 2) for e, E in curve(0.5) if e < EPS - 1e-9)
    ymax = 1.08 * max(E for _, E in curve(0.0) + curve(0.5))
    body = rf"""\begin{{groupplot}}[group style={{group size=2 by 1,horizontal sep=1.5cm}},width=.47\linewidth,height=5.4cm,grid=major,grid style={{gray!15}},tick label style={{font=\small}},label style={{font=\small}},{LEG}]
\nextgroupplot[xlabel={{error bound $\varepsilon$}},ylabel={{$\mathcal E(\varepsilon)/E_\kappa$}},xmin=0.03,xmax=0.51,ymin=-0.03,ymax={ymax:.3f},legend pos=north east]
\addplot[blue,thick,mark=*,mark size=1.3pt] table {table(["eps", "E"], curve(0.5))};\addlegendentry{{$\mu=1/2$}}
\addplot[red,thick,dashed,mark=triangle*,mark size=1.6pt] table {table(["eps", "E"], curve(0.0))};\addlegendentry{{$\mu=0$}}
\addplot[black,dotted,thick,domain=0.03:0.18169,samples=60]{{(0.5-1/pi-x)^2/(0.5-4/pi^2)}};\addlegendentry{{$\delta^2/B$}}
\draw[gray,densely dashdotted] (axis cs:0.18169,-0.03) -- (axis cs:0.18169,{ymax:.3f});
\node[font=\scriptsize,anchor=south west] at (axis cs:0.185,0) {{$\varepsilon_*$}};
\nextgroupplot[xlabel={{$\delta=\varepsilon_*-\varepsilon$}},ylabel={{$B\,\mathcal E/(E_\kappa\delta^2)$}},xmin=0,xmax={max(d for d, _ in ratio)*1.04:.3f},legend pos=north west]
\addplot[blue,thick,mark=*,mark size=1.3pt] table {table(["delta", "ratio"], ratio)};\addlegendentry{{numerical}}
\addplot[black,dashed,domain=0:0.15]{{1+3.2308451495*x}};\addlegendentry{{$1+c_3\delta$}}
\addplot[gray,dotted,domain=0:0.15,forget plot]{{1}};
"""
    (figs / "numerics_frontier.tex").write_text(wrap(f"% truncation |l| <= {N}\n" + body))


def crossover():
    c = read("crossover.csv")
    sets = {}
    for omega, sign, key in ((1e-3, 1, "a"), (4e-3, 1, "b"), (1.6e-2, 1, "c"), (1e-3, -1, "n")):
        rows = []
        for r in c:
            if abs(float(r["omega"]) - omega) < 1e-12 and np.sign(float(r["nu"])) == sign:
                rows.append((float(r["zeta"]), float(r["M_plus_nu"]) / omega ** (4 / 3),
                             -np.sign(float(r["nu"])) * float(r["two_p"]) / (2 * omega ** (1 / 3))))
        sets[key] = rows
    style = {"a": r"blue,only marks,mark=*,mark size=1.5pt",
             "b": r"red,only marks,mark=triangle*,mark size=1.8pt",
             "c": r"green!50!black,only marks,mark=square*,mark size=1.4pt",
             "n": r"black,only marks,mark=o,mark size=2.6pt"}
    label = {"a": r"$|\nu|=10^{-3}$", "b": r"$|\nu|=4\cdot10^{-3}$",
             "c": r"$|\nu|=1.6\cdot10^{-2}$", "n": r"$\nu=-10^{-3}$"}
    present = [k for k in "abcn" if sets[k]]  # skip empty series so legend entries stay aligned
    left = "".join(rf"\addplot[{style[k]}] table[x=zeta,y=scaled] {table(['zeta', 'scaled', 'current'], sets[k])};\addlegendentry{{{label[k]}}}" + "\n" for k in present)
    right = "".join(rf"\addplot[{style[k]}] table[x=zeta,y=current] {table(['zeta', 'scaled', 'current'], sets[k])};" + "\n" for k in present)
    body = rf"""\begin{{groupplot}}[group style={{group size=2 by 1,horizontal sep=1.5cm}},width=.47\linewidth,height=5.4cm,grid=major,grid style={{gray!15}},xlabel={{$\zeta=\delta/|\nu|^{{2/3}}$}},xmin=-1.7,xmax=2.2,tick label style={{font=\small}},label style={{font=\small}},{LEG}]
\nextgroupplot[ylabel={{$(M+\nu)/|\nu|^{{4/3}}$}},legend pos=north west]
\addplot[black,thick,domain=.03:1.8,samples=160,variable=\t] {PHI_PARAM};\addlegendentry{{$\Phi(\zeta)$}}
{left}\nextgroupplot[ylabel={{$-\sgn(\nu)\,p/|\nu|^{{1/3}}$}},ymin=0,legend pos=north east]
\addplot[black,thick,domain=.03:1.8,samples=160,variable=\t] {SIG_PARAM};\addlegendentry{{$\sigma_*(\zeta)$}}
{right}"""
    (figs / "numerics_crossover.tex").write_text(wrap(body))


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--data", type=Path, default=data)
    ap.add_argument("--out", type=Path, default=figs)
    ap.add_argument("--standalone", action="store_true")
    a = ap.parse_args()
    data, figs, STANDALONE = a.data, a.out, a.standalone
    figs.mkdir(parents=True, exist_ok=True)
    frontier(); crossover()
    print("wrote", figs / "numerics_frontier.tex", figs / "numerics_crossover.tex")
